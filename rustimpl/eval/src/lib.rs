//! Evaluation helpers for interpreter runtime behavior.

#[must_use]
/// Adds two unsigned integers.
pub const fn add(left: u64, right: u64) -> u64 {
    left + right
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn it_works() {
        let result = add(2, 2);
        assert_eq!(result, 4);
    }
}
